@app.delete("/api/accounts/<username>")
@mutating
def api_delete_account(username: str):
    username = unquote(username).lower()
    with connect() as connection:
        current = require_session(connection, master=True)
        if username in {current[0]["username"], current[0]["actor_username"]}:
            raise ApiError(409, "You cannot remove your active account")
        account = load_account(connection, username)
        if not account:
            raise ApiError(404, "Account not found")
        if account.get("role") == "master":
            rows = connection.execute("SELECT payload FROM accounts").fetchall()
            if sum(json.loads(row["payload"]).get("role") == "master" for row in rows) <= 1:
                raise ApiError(409, "The last master cannot be removed")
        connection.execute("DELETE FROM sessions WHERE username=%s OR actor_username=%s", (username, username))
        connection.execute("DELETE FROM accounts WHERE username=%s", (username,))
        audit(connection, current[0]["username"], "deleted", "account", username)
    return no_content()


