class ApiError(Exception):
    def __init__(self, status: int, message: str):
        super().__init__(message)
        self.status = status
        self.message = message


def utc_iso() -> str:
    return datetime.now(timezone.utc).isoformat()


def active_shift_context(now: datetime | None = None) -> dict:
    zone = ZoneInfo(MIS_TIMEZONE)
    local = now.astimezone(zone) if now else datetime.now(zone)
    hour = local.hour
    if 6 <= hour < 14:
        shift, start, end = "A", "06:00", "14:00"
        operational_date = local.date()
    elif 14 <= hour < 22:
        shift, start, end = "B", "14:00", "22:00"
        operational_date = local.date()
    else:
        shift, start, end = "C", "22:00", "06:00"
        operational_date = local.date() - timedelta(days=1) if hour < 6 else local.date()
    return {
        "date": operational_date.isoformat(),
        "shift": shift,
        "hours": f"{start} – {end}",
        "timezone": MIS_TIMEZONE,
        "serverTime": local.isoformat(),
    }


def database_url() -> str:
    url = os.environ.get("DATABASE_URL", "").strip()
    if not url:
        raise ApiError(503, "Database unavailable")
    return url


def connect() -> psycopg.Connection:
    # prepare_threshold=None is required for Neon/Vercel pooled (PgBouncer) URLs.
    return psycopg.connect(database_url(), row_factory=dict_row, prepare_threshold=None)


def initialize_database() -> None:
    global _db_ready
    if _db_ready:
        return
    with connect() as connection:
        for statement in SCHEMA_STATEMENTS:
            connection.execute(statement)
    _db_ready = True


def password_credential(password: str) -> dict:
    salt = secrets.token_bytes(16)
    digest = hashlib.pbkdf2_hmac("sha256", password.encode(), salt, PBKDF2_ITERATIONS)
    return {"passwordHash": digest.hex(), "salt": salt.hex(), "iterations": PBKDF2_ITERATIONS}


def valid_password(password: str) -> bool:
    return len(password) >= 8 and any(c.isalpha() for c in password) and any(c.isdigit() for c in password)


def verify_password(password: str, account: dict) -> bool:
    try:
        iterations = int(account.get("iterations", 0))
        salt = bytes.fromhex(account["salt"])
        expected = account["passwordHash"]
        if iterations <= 0 or len(salt) < 8:
            return False
        actual = hashlib.pbkdf2_hmac("sha256", password.encode(), salt, iterations).hex()
        return hmac.compare_digest(actual, expected)
    except (KeyError, TypeError, ValueError):
        return False


def public_account(account: dict) -> dict:
    return {k: v for k, v in account.items() if k not in {"passwordHash", "salt", "iterations"}}


def load_account(connection: psycopg.Connection, username: str) -> dict | None:
    row = connection.execute("SELECT payload FROM accounts WHERE username = %s", (username.lower(),)).fetchone()
    return json.loads(row["payload"]) if row else None


def store_account(connection: psycopg.Connection, username: str, account: dict) -> None:
    username = username.lower()
    account["username"] = username
    connection.execute(
        """INSERT INTO accounts(username,payload,updated_at) VALUES (%s,%s,%s)
           ON CONFLICT(username) DO UPDATE SET payload=EXCLUDED.payload,updated_at=EXCLUDED.updated_at""",
        (username, json.dumps(account, ensure_ascii=False), utc_iso()),
    )


def audit(connection, actor, action, entity, entity_id=None, detail=None) -> None:
    connection.execute(
        "INSERT INTO audit_log(occurred_at,actor,action,entity,entity_id,detail) VALUES (%s,%s,%s,%s,%s,%s)",
        (utc_iso(), actor, action, entity, entity_id, json.dumps(detail or {}, ensure_ascii=False)),
    )


def json_response(value, status=200, cookie: tuple[str, str] | None = None) -> Response:
    body = json.dumps(value, ensure_ascii=False, separators=(",", ":"))
    response = Response(body, status=status, mimetype="application/json; charset=utf-8")
    response.headers["Cache-Control"] = "no-store"
    if cookie:
        name, value = cookie
        max_age = 0 if value == "" else SESSION_SECONDS
        response.set_cookie(
            name,
            value,
            max_age=max_age,
            path="/",
            httponly=True,
            samesite="Strict",
            secure=SECURE_COOKIES,
        )
    return response


def no_content(clear_session: bool = False) -> Response:
    response = Response(status=204)
    response.headers["Cache-Control"] = "no-store"
    if clear_session:
        response.set_cookie(
            "mis_session",
            "",
            max_age=0,
            path="/",
            httponly=True,
            samesite="Strict",
            secure=SECURE_COOKIES,
        )
    return response


def read_json_object(allow_empty: bool = False) -> dict:
    raw = request.get_data(cache=True) or b""
    if not raw:
        if allow_empty:
            return {}
        raise ApiError(400, "Request body must be between 1 byte and 2 MB")
    if len(raw) > MAX_BODY_BYTES:
        raise ApiError(400, "Request body must be between 1 byte and 2 MB")
    try:
        value = json.loads(raw.decode())
    except (UnicodeDecodeError, json.JSONDecodeError) as exc:
        raise ApiError(400, "Request body must be valid JSON") from exc
    if not isinstance(value, dict):
        raise ApiError(400, "Request body must be a JSON object")
    return value


def reject_cross_site_write() -> None:
    if request.headers.get("Sec-Fetch-Site", "") == "cross-site":
        raise ApiError(403, "Cross-site requests are not allowed")
    origin = request.headers.get("Origin")
    allowed_origin = PUBLIC_ORIGIN or request.host_url.rstrip("/")
    if origin and allowed_origin and origin.rstrip("/") != allowed_origin:
        raise ApiError(403, "Invalid request origin")


def mutating(fn):
    @wraps(fn)
    def wrapped(*args, **kwargs):
        reject_cross_site_write()
        return fn(*args, **kwargs)

    return wrapped


def token_hash() -> str | None:
    value = request.cookies.get("mis_session")
    return hashlib.sha256(value.encode()).hexdigest() if value else None


def current_session(connection):
    hashed = token_hash()
    if not hashed:
        return None
    now = int(time.time())
    connection.execute("DELETE FROM sessions WHERE expires_at <= %s", (now,))
    row = connection.execute(
        "SELECT token_hash,username,actor_username,expires_at FROM sessions WHERE token_hash=%s",
        (hashed,),
    ).fetchone()
    if not row:
        return None
    account = load_account(connection, row["username"])
    return (row, account) if account else None


def require_session(connection, master=False):
    current = current_session(connection)
    if not current:
        raise ApiError(401, "Please sign in")
    if master and current[1].get("role") != "master":
        raise ApiError(403, "Master access is required")
    return current


def session_view(connection, row, account):
    value = {
        "username": row["username"],
        "displayName": account.get("displayName") or row["username"],
        "role": account.get("role", "user"),
        "expiresAt": row["expires_at"] * 1000,
    }
    if row["actor_username"]:
        actor = load_account(connection, row["actor_username"])
        if actor:
            value["impersonator"] = {
                "username": row["actor_username"],
                "displayName": actor.get("displayName") or row["actor_username"],
                "role": actor.get("role", "master"),
                "expiresAt": row["expires_at"] * 1000,
            }
    return value


def create_session(connection, username, actor=None):
    token = secrets.token_urlsafe(32)
    hashed = hashlib.sha256(token.encode()).hexdigest()
    now, expires = int(time.time()), int(time.time()) + SESSION_SECONDS
    connection.execute(
        "INSERT INTO sessions(token_hash,username,actor_username,created_at,expires_at) VALUES (%s,%s,%s,%s,%s)",
        (hashed, username.lower(), actor, now, expires),
    )
    row = connection.execute(
        "SELECT token_hash,username,actor_username,expires_at FROM sessions WHERE token_hash=%s",
        (hashed,),
    ).fetchone()
    return session_view(connection, row, load_account(connection, username)), token


@app.before_request
def ensure_database():
    if request.path == "/api/health":
        return
    try:
        initialize_database()
    except (ApiError, psycopg.Error) as exc:
        if isinstance(exc, ApiError):
            raise
        raise ApiError(503, "Database unavailable") from exc


@app.after_request
def add_security_headers(response: Response) -> Response:
    for name, value in SECURITY_HEADERS.items():
        response.headers.setdefault(name, value)
    return response


@app.errorhandler(ApiError)
def handle_api_error(exc: ApiError):
    return json_response({"error": exc.message}, exc.status)


@app.errorhandler(404)
def handle_not_found(_exc):
    if request.path.startswith("/api/"):
        return json_response({"error": "Unknown API endpoint"}, 404)
    return Response("Not found", status=404)


@app.errorhandler(413)
def handle_too_large(_exc):
    return json_response({"error": "Request body must be between 1 byte and 2 MB"}, 400)


